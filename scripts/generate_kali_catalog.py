#!/usr/bin/env python3
"""Generate the Go scanner catalog from the Kali tool catalog.

The Python worker owns the real command templates and parsers. This script
keeps the API catalog in sync with the tool names, labels, categories and
intrusive classification without duplicating command logic in Go.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "apps" / "scanner-workers"))

from km_worker.kali_tools import KALI_TOOLS  # noqa: E402

OUT = ROOT / "apps" / "api" / "internal" / "scanner" / "kali_catalog.go"


def go_string(value: str) -> str:
    return json.dumps(value, ensure_ascii=False)


def main() -> None:
    lines = [
        "package scanner",
        "",
        "// Code generated by scripts/generate_kali_catalog.py. Do not edit by hand.",
        "",
        "type kaliTool struct {",
        "\tname        string",
        "\tlabel       string",
        "\tcategory    string",
        "\tbinary      string",
        "\tdescription string",
        "\tintrusive   bool",
        "}",
        "",
        "var kaliTools = []kaliTool{",
    ]
    for tool in KALI_TOOLS:
        lines.append(
            "\t{"
            + ", ".join(
                [
                    go_string(tool["name"]),
                    go_string(tool["label"]),
                    go_string(tool["category"]),
                    go_string(tool.get("binary", tool["name"])),
                    go_string(tool["description"]),
                    "true" if tool.get("intrusive") else "false",
                ]
            )
            + "},"
        )
    lines += [
        "}",
        "",
        "func init() {",
        "\tfor _, tool := range kaliTools {",
        "\t\tCatalog = append(Catalog, Meta{",
        "\t\t\tName:          tool.name,",
        "\t\t\tLabel:         tool.label,",
        "\t\t\tCategory:      tool.category,",
        "\t\t\tBinary:        tool.binary,",
        "\t\t\tDescription:   tool.description,",
        "\t\t\tIntrusive:     tool.intrusive,",
        "\t\t\tParams:        map[string]ParamSchema{},",
        "\t\t\tDefaultParams: map[string]any{},",
        "\t\t})",
        "\t}",
        "}",
        "",
    ]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} with {len(KALI_TOOLS)} tools")


if __name__ == "__main__":
    main()
